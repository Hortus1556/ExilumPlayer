"""import.py <work dir>: brings FFmpeg into renderer/src/main/cpp/ffmpeg as the build there needs it.

The work dir holds the unpacked release (ffmpeg-<version>) and one build of it for each ABI (build-<abi>), configured
by configure-android.sh and built with make. Each build leaves, beside its objects, the list of every file the
compiler read for it. From those lists this copies:

  - the sources the build compiled, and the headers and .c templates they include: a fifteenth of the release;
  - what configure generated - config.h, the lists of codecs and demuxers - for each ABI, under config/<abi>;
  - sources.cmake, the compiled sources by library, which CMakeLists.txt includes.

Run from the repository's root. What was there before is replaced.
"""
import os
import re
import shutil
import sys

WORK = os.path.abspath(sys.argv[1]).replace('\\', '/')
ABIS = ['arm64-v8a', 'armeabi-v7a']
LIBS = ['avutil', 'avcodec', 'avformat', 'swresample']
OUT = 'renderer/src/main/cpp/ffmpeg'

release = [d for d in os.listdir(WORK) if re.fullmatch(r'ffmpeg-[0-9.]+', d)]
assert len(release) == 1, release
SRC = WORK + '/' + release[0]
VERSION = release[0][len('ffmpeg-'):]


def norm(p):
    return os.path.normpath(p).replace('\\', '/')


def within(full, base):
    return full.lower().startswith(base.lower() + '/')


sources = set()
generated = {abi: set() for abi in ABIS}
compiled = {abi: set() for abi in ABIS}
for abi in ABIS:
    build = WORK + '/build-' + abi
    for root, _, names in os.walk(build):
        for name in names:
            if not name.endswith('.d'):
                continue
            text = open(os.path.join(root, name), encoding='utf-8', errors='replace').read().replace('\\\n', ' ')
            for dep in text[text.index(': ') + 2:].split():
                absolute = re.match(r'^[A-Za-z]:', dep) or dep.startswith('/')
                full = norm(dep if absolute else os.path.join(build, dep))
                if within(full, SRC):
                    sources.add(full[len(SRC) + 1:])
                elif within(full, build):
                    generated[abi].add(full[len(build) + 1:])
            compiled[abi].add(norm(os.path.join(root, name))[len(build) + 1:-2] + '.c')
assert compiled[ABIS[0]] == compiled[ABIS[1]], 'the ABIs compile different sources'
assert all(c in sources for c in compiled[ABIS[0]]), 'a compiled source the compiler did not read'

if os.path.isdir(OUT):
    shutil.rmtree(OUT)
for rel in sorted(sources):
    os.makedirs(os.path.dirname(OUT + '/' + rel), exist_ok=True)
    shutil.copyfile(SRC + '/' + rel, OUT + '/' + rel)
for name in ('COPYING.LGPLv2.1', 'LICENSE.md', 'CREDITS', 'RELEASE'):
    shutil.copyfile(SRC + '/' + name, OUT + '/' + name)

for abi in ABIS:
    for rel in sorted(generated[abi]):
        target = '%s/config/%s/%s' % (OUT, abi, rel)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        text = open('%s/build-%s/%s' % (WORK, abi, rel), encoding='utf-8').read()
        if rel == 'config.h':
            # Not the paths of the machine it was configured on.
            text = re.sub(r'#define FFMPEG_CONFIGURATION ".*"',
                          '#define FFMPEG_CONFIGURATION "audio decoders only: see tools/ffmpeg/configure-android.sh"', text)
            text = re.sub(r'#define CC_IDENT ".*"', '#define CC_IDENT "Android NDK clang"', text)
        open(target, 'w', encoding='utf-8', newline='\n').write(text)

lines = ['# Generated by tools/ffmpeg/import.py from FFmpeg %s: the sources each library is built from.' % VERSION, '']
for lib in LIBS:
    mine = sorted(c for c in compiled[ABIS[0]] if c.startswith('lib%s/' % lib))
    lines.append('set(FFMPEG_%s_SOURCES' % lib.upper())
    lines += ['        ' + c for c in mine]
    lines.append(')')
    lines.append('')
other = sorted(c for c in compiled[ABIS[0]] if not any(c.startswith('lib%s/' % lib) for lib in LIBS))
lines.append('# Stand-ins for what the C library lacks; built into avutil.')
lines.append('set(FFMPEG_COMPAT_SOURCES')
lines += ['        ' + c for c in other]
lines.append(')')
open(OUT + '/sources.cmake', 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')

size = sum(os.path.getsize(os.path.join(r, n)) for r, _, ns in os.walk(OUT) for n in ns)
print('FFmpeg %s: %d files copied, %d compiled, %d KB in %s' % (VERSION, len(sources), len(compiled[ABIS[0]]), size // 1024, OUT))
print('outside the four libraries:', other)
